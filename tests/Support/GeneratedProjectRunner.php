<?php

declare(strict_types=1);

namespace Vusys\Zefram\Tests\Support;

/**
 * Turns a written GraphGenerator (#1) graph into a runnable, zefram-enabled PHPUnit project
 * and runs it through a real child process, reusing #2's ChildPhpUnitProcess/JUnitReport
 * machinery rather than duplicating it.
 *
 * GraphGenerator itself stays framework-agnostic (reusable for non-zefram perf/paratest
 * fixtures too, see #1) — this class is where the generated tests get wired up with
 * ZeframAware and given a phpunit.xml + combined bootstrap. Unlike DogfoodRunner, this
 * reuses the *real* installed Zefram classes from the outer vendor/autoload.php: there's no
 * need for a mutable copy of the package's own source here, only of the generated graph.
 */
final readonly class GeneratedProjectRunner
{
    use ReadsZeframShards;

    public function __construct(private GraphGenerator $graph)
    {
        $this->graph->write();
        $this->zeframifyGeneratedTests();

        file_put_contents($this->bootstrapPath(), $this->renderBootstrap());
        file_put_contents($this->phpUnitConfigPath(), $this->renderPhpUnitConfig());
    }

    public static function pcovAvailable(): bool
    {
        return ChildPhpUnitProcess::pcovAvailable();
    }

    public function run(): ChildRunResult
    {
        return (new ChildPhpUnitProcess)->run($this->graph->root, $this->phpUnitConfigPath());
    }

    public function graph(): GraphGenerator
    {
        return $this->graph;
    }

    public function cacheRoot(): string
    {
        return $this->graph->root;
    }

    public function destroy(): void
    {
        $this->graph->destroy();
    }

    private function bootstrapPath(): string
    {
        return $this->graph->root.'/e2e-bootstrap.php';
    }

    private function phpUnitConfigPath(): string
    {
        return $this->graph->root.'/phpunit.xml';
    }

    /**
     * The generator's own test classes are plain `extends TestCase` with no setUp() to
     * shadow — simpler than DogfoodRunner's zeframify(): just import and `use` the trait.
     */
    private function zeframifyGeneratedTests(): void
    {
        foreach ($this->graph->nodeNames() as $name) {
            $path = $this->graph->testPath($name);
            $content = (string) file_get_contents($path);

            $content = (string) preg_replace(
                '/^use PHPUnit\\\\Framework\\\\TestCase;$/m',
                "use PHPUnit\\\\Framework\\\\TestCase;\nuse Vusys\\\\Zefram\\\\ZeframAware;",
                $content,
                1,
            );

            $content = (string) preg_replace(
                '/((?:final\s+)?class\s+\w+\s+extends\s+TestCase\s*\n\{\n)/',
                '$1    use ZeframAware;'."\n\n",
                $content,
                1,
            );

            file_put_contents($path, $content);
        }
    }

    private function renderBootstrap(): string
    {
        $outerAutoload = addslashes(dirname(__DIR__, 2).'/vendor/autoload.php');
        $graphBootstrap = addslashes($this->graph->bootstrapPath());

        return <<<PHP
<?php

declare(strict_types=1);

// Generated by Vusys\Zefram\Tests\Support\GeneratedProjectRunner. Outer vendor/autoload.php
// supplies PHPUnit and the real installed Zefram classes; the graph's own bootstrap supplies
// its generated namespace's autoloader.
require '{$outerAutoload}';
require '{$graphBootstrap}';

PHP;
    }

    private function renderPhpUnitConfig(): string
    {
        $root = htmlspecialchars($this->graph->root, ENT_XML1);

        return <<<XML
<?xml version="1.0" encoding="UTF-8"?>
<phpunit xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
         xsi:noNamespaceSchemaLocation="vendor/phpunit/phpunit/phpunit.xsd"
         bootstrap="{$root}/e2e-bootstrap.php"
         cacheDirectory="{$root}/.phpunit.cache"
         failOnRisky="true"
         failOnWarning="true">
    <testsuites>
        <testsuite name="generated">
            <directory>{$root}/tests</directory>
        </testsuite>
    </testsuites>
    <extensions>
        <bootstrap class="Vusys\\Zefram\\PhpUnit\\ZeframExtension">
            <parameter name="cacheDirectory" value=".zefram"/>
        </bootstrap>
    </extensions>
    <source>
        <include>
            <directory>{$root}/src</directory>
        </include>
    </source>
</phpunit>

XML;
    }
}
